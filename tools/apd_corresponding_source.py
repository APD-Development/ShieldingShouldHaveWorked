"""Package pinned TEST341 source with its exact runtime assets, never Git/key history.

This does not publish, sign or claim old binaries are license-correct. It records
signing-only source substitutions and recovers generated compilation inputs.
"""
import argparse,hashlib,io,json,pathlib,re,subprocess,tarfile,zipfile
ROOT=pathlib.Path(__file__).resolve().parents[1]
COMMIT='acb69c653033ee0d8df68264395ca27e08eb566d'
VARIANTS={'Developer':('ad6281b3e41fe414187ca40824157a5bbcf102d7d86e569dbdb8439e7f47d694','C341',True),'Alpha-Testers':('639ce15ddb4b02d037cd29f995c9f38514e03cf577370cf38488f4602bfd65bd','P341',False)}
def sha(data):return hashlib.sha256(data).hexdigest()
def package(apk,variant,target):
 expected,build,test=VARIANTS[variant];apk=pathlib.Path(apk)
 if sha(apk.read_bytes())!=expected:raise ValueError('APK checksum is not the verified TEST341 variant')
 archive=subprocess.check_output(['git','archive',COMMIT],cwd=ROOT)
 files={};removed=[]
 with tarfile.open(fileobj=io.BytesIO(archive)) as tf:
  for member in tf:
   if not member.isfile():continue
   name=member.name
   if name.startswith('keystore/') or name.lower().endswith(('.jks','.keystore','.p12','.pfx')):
    removed.append(name);continue
   files[name]=tf.extractfile(member).read()
 # Derive the historically exposed credential privately; never print or persist it.
 gradle=files['android/build.gradle'].decode();credentials=set(re.findall(r"(?:storePassword|keyPassword)\s+'([^']+)'",gradle))
 transformations=[]
 for name,data in list(files.items()):
  try:text=data.decode('utf-8')
  except UnicodeDecodeError:continue
  sanitized=text
  for value in credentials:sanitized=sanitized.replace(value,'EXTERNAL_SIGNING_PASSWORD')
  if sanitized!=text:
   transformations.append({'path':name,'original_sha256':sha(data),'reason':'remove historically exposed signing password; no application logic alteration'})
   files[name]=sanitized.encode()
 gradle=files['android/build.gradle'].decode()
 gradle=gradle.replace("rootProject.file('keystore/apd-debug.jks')","rootProject.file(System.getenv('APD_SIGNING_KEYSTORE') ?: 'keystore/EXTERNAL-KEY-REQUIRED.jks')")
 gradle=re.sub(r"storePassword\s+'EXTERNAL_SIGNING_PASSWORD'","storePassword System.getenv('APD_SIGNING_STORE_PASSWORD') ?: ''",gradle)
 gradle=re.sub(r"keyPassword\s+'EXTERNAL_SIGNING_PASSWORD'","keyPassword System.getenv('APD_SIGNING_KEY_PASSWORD') ?: System.getenv('APD_SIGNING_STORE_PASSWORD') ?: ''",gradle)
 gradle=gradle.replace('signingConfig signingConfigs.apdDebug',"signingConfig project.hasProperty('apdUnsignedVerification') ? null : signingConfigs.apdDebug")
 files['android/build.gradle']=gradle.encode()
 transformations.append({'path':'android/build.gradle','reason':'external signing and explicit unsigned reconstruction switch only; original application ID/version/source unchanged'})
 recovered=[]
 with zipfile.ZipFile(apk) as z:
  for n in sorted(z.namelist()):
   if not n.startswith('assets/') or n.endswith('/'):continue
   relative=n[len('assets/'):]
   if relative=='apd/features.txt':
    if not test or z.read(n)!=b'testBuild\ngrudge\ndemoUnlock\nclericPlayable\n':raise ValueError('Unexpected developer feature input')
    files['CORRESPONDING-SOURCE/generated-inputs/apd/features.txt']=z.read(n)
    continue # Generated by the unmodified -PapdTestBuild Gradle code.
   path='core/src/main/assets/'+relative;data=z.read(n)
   if files.get(path)!=data:recovered.append({'path':path,'sha256':sha(data),'origin':'exact verified APK runtime asset'})
   files[path]=data
 recipe=f'./gradlew :core:test :android:assembleDebug -PapdUnsignedVerification -PapdBuild={build}'+(' -PapdTestBuild' if test else '')
 readme=f'''# APD TEST341 {variant} corresponding source

Original producing commit: {COMMIT}; existing tag: apd-alpha-preview-341.
APK SHA-256: {expected}.
Application ID com.charltonchris29.adhdpixeldungeon.indev; versionCode 920.

Use JDK 21, Android SDK platform 36/build tools selected by the included Gradle scripts, and the included Gradle 9.5 wrapper. Install the Android SDK and set ANDROID_HOME or local.properties before building. Network access is needed for the pinned build dependencies.

{recipe}

This builds an UNSIGNED reconstruction. For install-over updates, supply the original external key environment variables and omit -PapdUnsignedVerification. No signing key/password or Git history is included. Recipients may sign their own copies with their own key; a different key cannot update existing installations. Never uninstall or clear player data to work around that restriction.

All 366 generated history TSVs and exact runtime assets were recovered from the checksum-verified binary. Developer features are generated by -PapdTestBuild; a copy is supplied as an audit input outside the asset root. No game logic, scoring value, or saved-data format was changed. Signing configuration and exposed credentials alone are sanitized; every substitution is in manifest.json.

This archive supplies source for the already distributed historical binary. TEST341 still uses the GPL-incompatible historical JSON dependency; that binary is not retroactively fixed by this archive. The replacement is in the GPL compliance PR. Compilation/byte-for-byte reconstruction validation is reported separately, never inferred from successful packaging. GPL terms and upstream notices remain included.
'''
 files['CORRESPONDING-SOURCE/README.txt']=readme.encode()
 manifest={'source_commit':COMMIT,'source_tag':'apd-alpha-preview-341','variant':variant,'apk_sha256':expected,'removed_signing_files':removed,'signing_only_transformations':transformations,'recovered_generated_assets':recovered,'history_tsv_count':sum(n.startswith('core/src/main/assets/apd/history/') and n.endswith('.tsv') for n in files),'build_recipe':recipe,'compiled_reconstruction_verified':False,'files':{n:sha(b) for n,b in sorted(files.items())}}
 if manifest['history_tsv_count']!=366:raise ValueError('Incomplete generated history')
 for n,b in files.items():
  if n.startswith('/') or '..' in pathlib.PurePosixPath(n).parts:raise ValueError('Unsafe path')
  if any(v.encode() in b for v in credentials):raise ValueError('Credential not removed')
 files['CORRESPONDING-SOURCE/manifest.json']=(json.dumps(manifest,indent=2)+'\n').encode()
 target=pathlib.Path(target);target.parent.mkdir(parents=True,exist_ok=True)
 with zipfile.ZipFile(target,'w',zipfile.ZIP_DEFLATED,compresslevel=9) as z:
  for n,b in sorted(files.items()):
   info=zipfile.ZipInfo('APD-Source-341-'+variant+'/'+n,date_time=(2026,10,30,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED
   info.external_attr=(0o100755 if n in ('gradlew','gradlew.bat') or n.endswith('.sh') else 0o100644)<<16
   z.writestr(info,b)
 checksum=sha(target.read_bytes());target.with_suffix(target.suffix+'.sha256').write_text(checksum+'  '+target.name+'\n')
 print(json.dumps({'archive':str(target),'sha256':checksum,'files':len(files),'recovered_assets':len(recovered),'history_tsv_count':366,'compiled_reconstruction_verified':False}))
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--apk',required=True);p.add_argument('--variant',choices=VARIANTS,required=True);p.add_argument('--output',required=True);a=p.parse_args();package(a.apk,a.variant,a.output)
