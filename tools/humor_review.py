#!/usr/bin/env python3
"""Lists the Cleric grudge line packs as a readable review document (docs/APD-VENDETTA-LINES.md).

Run from the repository root:  python3 -I tools/humor_review.py
Also prints the numbers a changelog footer may quote, computed from the pack and the committed id list of the previous release:
  added = ids in the packs that are not in core/src/test/resources/apd/cleric_complaint_ids.txt
Never type those numbers by hand.
"""
import glob, os, sys

ROOT = os.path.join('core', 'src', 'main', 'assets', 'apd', 'humor')
IDS = os.path.join('core', 'src', 'test', 'resources', 'apd', 'cleric_complaint_ids.txt')
OUT = os.path.join('docs', 'APD-VENDETTA-LINES.md')


def read_packs():
    packs = []
    names = [n.strip() for n in open(os.path.join(ROOT, 'packs.txt'), encoding='utf-8') if n.strip()]
    for name in names:
        rows = []
        for raw in open(os.path.join(ROOT, name), encoding='utf-8'):
            line = raw.rstrip('\n')
            if not line.strip() or line.startswith('#'):
                continue
            f = [x.strip() for x in line.split('|')]
            rows.append(f)
        packs.append((name, rows))
    return packs


def main():
    packs = read_packs()
    all_ids = [r[0] for _, rows in packs for r in rows]
    counted = [r[0] for _, rows in packs for r in rows if r[1] != 'meta']
    previous = set(l.strip() for l in open(IDS, encoding='utf-8') if l.strip() and not l.startswith('#'))
    added = [i for i in all_ids if i not in previous]
    adult = sum(1 for _, rows in packs for r in rows if r[6])
    out = ['# Cleric grudge: the lines, for review', '',
           'Generated by `tools/humor_review.py` from `core/src/main/assets/apd/humor/`. Edit the pack files, not this page.', '',
           f'- Lines: {len(all_ids)} ({len(counted)} counted as complaints, {len(all_ids) - len(counted)} meta)',
           f'- With stronger Adult wording: {adult}',
           f'- Added since the committed id list of the previous release: {len(added)}', '',
           'Each line has Clean wording (shown to everyone unless they chose Adult humor) and an optional Adult wording. "When" says what must be true of',
           'recorded facts for the line to be eligible; `{name}` is filled from a recorded value, never invented. Lines marked JOKE use invented numbers on purpose.', '']
    for name, rows in packs:
        out += [f'## {name}', '', '| id | category | when | Clean | Adult |', '|---|---|---|---|---|']
        for f in rows:
            flags = ' JOKE' if 'joke' in f[2] else ''
            esc = lambda s: s.replace('|', '/').replace('{', '\\{') if s else ''
            out.append(f'| {f[0]}{flags} | {f[1]} | {esc(f[3]) if f[3] != "-" else "any time"} | {esc(f[5])} | {esc(f[6])} |')
        out.append('')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out))
    print(f'{len(all_ids)} lines, {len(counted)} counted, {len(added)} added since the previous release list; wrote {OUT}')


if __name__ == '__main__':
    sys.exit(main())
